# ─── Database ─────────────────────────────────────────────────────────────────
# Development: SQLite
# Production:  PostgreSQL via DATABASE_URL environment variable
#
# Railway provides DATABASE_URL automatically when a PostgreSQL plugin is added.
# Format: postgres://USER:PASSWORD@HOST:PORT/DBNAME

_database_url = os.environ.get('DATABASE_URL', '')
if IS_PRODUCTION and not _database_url:
    from django.core.exceptions import ImproperlyConfigured
    raise ImproperlyConfigured('DATABASE_URL is required in production; SQLite is not supported for deployed data.')

if _database_url:
    # Parse the DATABASE_URL for PostgreSQL (Railway / Heroku style)
    from urllib.parse import parse_qs, unquote, urlparse
    _parsed = urlparse(_database_url)
    if _parsed.scheme not in {'postgres', 'postgresql'} or not _parsed.hostname or not _parsed.path.strip('/'):
        from django.core.exceptions import ImproperlyConfigured
        raise ImproperlyConfigured('DATABASE_URL must be a valid postgres:// or postgresql:// URL.')
    _database_query = parse_qs(_parsed.query)
    _database_options = {key: values[-1] for key, values in _database_query.items() if values}
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': unquote(_parsed.path.lstrip('/')),
            'USER': unquote(_parsed.username or ''),
            'PASSWORD': unquote(_parsed.password or ''),
            'HOST': _parsed.hostname,
            'PORT': str(_parsed.port or 5432),
            'OPTIONS': _database_options,
            'CONN_MAX_AGE': int(os.environ.get('DJANGO_DB_CONN_MAX_AGE', '60' if IS_PRODUCTION else '0')),
            'CONN_HEALTH_CHECKS': True,
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


